function seriesAround(change: number): number[] {
  const base = 1.4
  return Array.from({ length: 21 }, (_, index) => {
    const day = index - 10
    const drift = day * 0.03
    const jump = day >= 0 ? change : 0
    return Number((base + drift + jump + Math.sin(index / 3) * 0.08).toFixed(2))
  })
}

